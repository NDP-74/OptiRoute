CREATE TABLE IF NOT EXISTS planning_view (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_planning_view_owner ON planning_view(owner_id);

CREATE TABLE IF NOT EXISTS planning_view_row (
    view_id BIGINT NOT NULL REFERENCES planning_view(id) ON DELETE CASCADE,
    row_position INTEGER NOT NULL,
    row_type VARCHAR(24) NOT NULL,
    driver_id BIGINT,
    PRIMARY KEY (view_id, row_position),
    CHECK ((row_type = 'DRIVER' AND driver_id IS NOT NULL)
        OR (row_type = 'UNUSED_VEHICLES' AND driver_id IS NULL))
);
